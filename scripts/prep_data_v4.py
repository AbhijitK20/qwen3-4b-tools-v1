#!/usr/bin/env python3
"""V4 data pipeline — adds APIGen (109k verified tool-calling rows) + xlam-ru.

New sources vs v3:
  argilla/apigen-function-calling  109,402 rows. Salesforce APIGen pipeline,
      answers generated by Llama-3.1-70B / Qwen2.5-72B and filtered for
      validity. 50% multi-call. Every row has a non-empty `answers` and a
      non-empty `tools` list (verified on a 30k sample). This is the single
      largest quality jump available: 5x the size of the v3 corpus.
  belyakoff/xlam-ru-tool-calling  60,000 rows. An ungated mirror of xlam-60k
      BUT the queries/tool descriptions are RUSSIAN. Off-distribution for an
      English tool-calling eval, so it is CAPPED rather than excluded -- it
      still teaches call syntax, just not English semantics.

APIGen contains ZERO abstention examples (every row has answers), so it
strengthens the call axis and the multi-call axis only. The clarify share is
held at the v3 level by the quota logic, so the v3->v4 comparison stays a
clean test of "more call data".

Output: data/train_v4.jsonl, data/val_v4.jsonl
"""
import glob
import json
import random
import sys
from collections import Counter, defaultdict
from pathlib import Path

BASE = Path.home() / "model training"
CACHE = BASE / "hf_cache" / "hub"
random.seed(43)

sys.path.insert(0, str(BASE / "scripts"))
from prep_data_v3 import (  # noqa: E402
    conv_hash, load_hermes, load_when2call_pref, load_when2call_sft,
    normalize_tools, tools_usable, verify,
)

XLAM_RU_CAP = 6000      # capped: Russian queries, off-distribution for English eval

# Target mix. Clarify share is deliberately preserved at the v3 level so the
# delta measures added CALL data, not a rebalancing of call/clarify.
TARGETS = {
    "apigen": 0.34,
    "w2c_clarify": 0.26,
    "glaive_like": 0.18,
    "toolace": 0.09,
    "hermes": 0.09,
    "xlam_ru": XLAM_RU_CAP,
}


def load_apigen():
    """109k rows: query + tools(JSON str) + answers(JSON str)."""
    import pandas as pd
    files = sorted(glob.glob(str(CACHE / "datasets--argilla--apigen-function-calling/snapshots/*/data/*.parquet")))
    if not files:
        print("  apigen: NOT CACHED")
        return []
    kept, drop = [], Counter()
    n_calls = Counter()
    for fp in files:
        df = pd.read_parquet(fp)
        for _, row in df.iterrows():
            try:
                tools = json.loads(row["tools"]) if isinstance(row["tools"], str) else row["tools"]
                ans = json.loads(row["answers"]) if isinstance(row["answers"], str) else row["answers"]
            except Exception:  # noqa: BLE001
                drop["bad_json"] += 1
                continue
            if not tools:
                drop["no_tools"] += 1
                continue
            if not ans:
                drop["no_answer"] += 1
                continue
            # tools are bare function dicts -> wrap into the standard envelope
            wrapped = []
            for t in tools:
                if not isinstance(t, dict) or not t.get("name"):
                    continue
                wrapped.append({"type": "function", "function": {
                    "name": t.get("name"),
                    "description": t.get("description", ""),
                    "parameters": t.get("parameters", {}) or {},
                }})
            if not wrapped:
                drop["bad_tools"] += 1
                continue
            calls = []
            for a in ans:
                if not isinstance(a, dict) or not a.get("name"):
                    continue
                args = a.get("arguments")
                if not isinstance(args, dict):
                    args = {}
                calls.append({"function": {"name": a["name"], "arguments": args}})
            if not calls:
                drop["bad_calls"] += 1
                continue
            msgs = [
                {"role": "system", "content": "You are a helpful assistant with tools."},
                {"role": "user", "content": row["query"]},
                {"role": "assistant", "content": "", "tool_calls": calls},
            ]
            n_calls[len(calls)] += 1
            kept.append({"messages": msgs, "tools": wrapped, "source": "apigen"})
    multi = sum(v for k, v in n_calls.items() if k > 1)
    print(f"  apigen: {len(kept):6d} kept | multi-call {multi} "
          f"({multi/max(len(kept),1):.0%}) | dropped {dict(drop)}")
    return kept


def load_xlam_ru():
    """60k xlam mirror, Russian. Capped hard."""
    import pandas as pd
    files = sorted(glob.glob(str(CACHE / "datasets--belyakoff--xlam-ru-tool-calling/snapshots/*/data/*.parquet")))
    if not files:
        print("  xlam_ru: NOT CACHED")
        return []
    kept, drop = [], Counter()
    for fp in files:
        df = pd.read_parquet(fp)
        for _, row in df.iterrows():
            try:
                tools = json.loads(row["tools"]) if isinstance(row["tools"], str) else row["tools"]
                ans = json.loads(row["answers"]) if isinstance(row["answers"], str) else row["answers"]
            except Exception:  # noqa: BLE001
                drop["bad_json"] += 1
                continue
            if not tools or not ans:
                drop["empty"] += 1
                continue
            wrapped = [{"type": "function", "function": {
                "name": t.get("name"), "description": t.get("description", ""),
                "parameters": t.get("parameters", {}) or {}}}
                for t in tools if isinstance(t, dict) and t.get("name")]
            calls = [{"function": {"name": a["name"], "arguments": a.get("arguments") or {}}}
                     for a in ans if isinstance(a, dict) and a.get("name")]
            if not wrapped or not calls:
                drop["bad"] += 1
                continue
            kept.append({"messages": [
                {"role": "system", "content": "You are a helpful assistant with tools."},
                {"role": "user", "content": row["query"]},
                {"role": "assistant", "content": "", "tool_calls": calls},
            ], "tools": wrapped, "source": "xlam_ru"})
    random.shuffle(kept)
    capped = kept[:XLAM_RU_CAP]
    print(f"  xlam_ru: {len(kept)} avail -> capped to {len(capped)} (Russian, "
          f"off-distribution for English eval) | dropped {dict(drop)}")
    return capped


def main():
    print("[1] APIGen + xlam_ru")
    new = load_apigen() + load_xlam_ru()

    print("[2] v3 corpus (glaive/toolace/hermes only) + RAW clarify pool")
    # NOTE: do NOT reuse v3's w2c_clarify rows here. v3 already applied a 34%
    # cap, so its jsonl holds only 8,665 of the 15,165 available clarify
    # examples. Reload when2call from source to get the full pool back.
    v3 = []
    for fn in ("train_v3.jsonl", "val_v3.jsonl"):
        fp = BASE / "data" / fn
        if fp.exists():
            v3 += [json.loads(l) for l in open(fp)
                   if json.loads(l)["source"] != "w2c_clarify"]
    raw_clarify = load_when2call_sft() + load_when2call_pref()
    raw_clarify = [r for r in raw_clarify if r["source"] == "w2c_clarify"]
    v3 += raw_clarify
    print(f"  v3(no-clarify)={len(v3) - len(raw_clarify)} + raw clarify={len(raw_clarify)}")

    everything = v3 + new
    print(f"[3] combined raw: {len(everything)}")

    print("[4] verify")
    ok, reasons = [], Counter()
    for r in everything:
        good, why = verify(r)
        if good:
            ok.append(r)
        else:
            reasons[why] += 1
    print(f"  verified {len(ok)} (dropped {sum(reasons.values())})")
    for w, n in reasons.most_common(6):
        print(f"    {w}: {n}")

    print("[5] dedupe")
    seen, ded = set(), []
    for r in ok:
        h = conv_hash(r)
        if h in seen:
            continue
        seen.add(h)
        ded.append(r)
    print(f"  deduped -> {len(ded)}")

    print("[6] quotas")
    by = defaultdict(list)
    for r in ded:
        by[r["source"]].append(r)
    for v in by.values():
        random.shuffle(v)

    glaive_like = by.get("glaive", []) + by.get("glaive5k", [])
    hermes_like = (by.get("hermes", []) + by.get("hermes_agentic", [])
                   + by.get("when2call", []) + by.get("synth_agent", []))
    w2c_call = by.get("w2c_call", [])

    pools = {
        "apigen": by.get("apigen", []),
        "w2c_clarify": by.get("w2c_clarify", []),
        "glaive_like": glaive_like,
        "toolace": by.get("toolace", []),
        "hermes": hermes_like + w2c_call,
        "xlam_ru": by.get("xlam_ru", []),
    }
    n_target = 60000
    final = []
    for key, share in TARGETS.items():
        quota = XLAM_RU_CAP if key == "xlam_ru" else int(n_target * share)
        pool = pools[key]
        take = min(len(pool), quota)
        final += pool[:take]
        print(f"  {key:12s} pool={len(pool):6d} quota={quota:6d} kept={take:6d}")

    print("[7] clarify ratio target")
    TARGET_CLARIFY = 0.34
    calls = [r for r in final if any(m.get("tool_calls") for m in r["messages"])]
    nocalls = [r for r in final if not any(m.get("tool_calls") for m in r["messages"])]
    random.shuffle(nocalls)

    # Solve for the mix size that hits the target ratio with the clarify pool
    # we actually have: total = C + N, N/(C+N) = t  =>  N = C*t/(1-t)
    want_nocall = int(len(calls) * TARGET_CLARIFY / (1 - TARGET_CLARIFY))
    if len(nocalls) < want_nocall:
        # Not enough clarify available -- shrink the call side instead of
        # silently undershooting the ratio. This is what went wrong in v4.
        keep_calls = int(len(nocalls) * (1 - TARGET_CLARIFY) / TARGET_CLARIFY)
        print(f"  clarify pool short ({len(nocalls)} < {want_nocall}); "
              f"trimming calls {len(calls)} -> {keep_calls} to hold {TARGET_CLARIFY:.0%}")
        random.shuffle(calls)
        calls = calls[:keep_calls]
    else:
        nocalls = nocalls[:want_nocall]
    final = calls + nocalls
    random.shuffle(final)
    print(f"  calls={len(calls)} clarify={len(nocalls)} "
          f"({len(nocalls)/len(final):.1%} clarify, target {TARGET_CLARIFY:.0%})")

    for r in final:
        r["n_calls"] = sum(len(m.get("tool_calls") or []) for m in r["messages"])

    n_val = max(800, int(len(final) * 0.02))
    val, train = final[:n_val], final[n_val:]
    for split, data in (("train_v4", train), ("val_v4", val)):
        with open(BASE / "data" / f"{split}.jsonl", "w") as f:
            for r in data:
                f.write(json.dumps(r) + "\n")
    print(f"\nsaved train_v4={len(train)} val_v4={len(val)}")
    print("sources:", dict(Counter(r["source"] for r in train)))
    print("clarify:", sum(1 for r in train if r["n_calls"] == 0),
          f"({sum(1 for r in train if r['n_calls']==0)/len(train):.1%})")
    print("multi-call:", sum(1 for r in train if r["n_calls"] > 1))


if __name__ == "__main__":
    main()